/// Emits a complete WGSL module from a `KernelSpec` and `Schedule`.
pub fn emit_wgsl(kernel: &KernelSpec, schedule: Schedule) -> Result<GeneratedShader, ForgeError> {
    kernel.validate()?;
    let semantic_hash = kernel.semantic_hash()?;
    let mut source = String::with_capacity(2_048);
    writeln!(
        source,
        "// Generated by Etalon WGSL Forge schema {FORGE_SCHEMA_VERSION}.\n// Kernel: {}@{}\n// Semantic hash: {semantic_hash}\n// Schedule: workgroup={}, items={}, vector={}",
        kernel.id,
        kernel.semantic_version,
        schedule.effective_workgroup_size(),
        schedule.items_per_invocation,
        schedule.vector_width
    )
    .map_err(|error| ForgeError::Emission(error.to_string()))?;

    emit_kernel_body(&mut source, kernel, schedule)?;

    let source_hash = blake3::hash(source.as_bytes()).to_hex().to_string();
    Ok(GeneratedShader {
        kernel_id: kernel.id.clone(),
        semantic_hash,
        source_hash,
        schedule,
        source,
    })
}

/// Emits a WGSL shader string from a high-level `Op` and `Schedule`.
pub fn emit_wgsl_kernel(op: &Op, sched: &Schedule) -> Result<String, ForgeError> {
    let wg = sched.effective_workgroup_size();
    match op {
        Op::MatMul { tc: true, .. } => {
            if sched.tile.m <= 4 {
                return Ok(emit_wgsl(&BuiltinKernel::Gemv.spec(), *sched)?.source);
            }
            let shape = CoopMatShape::f32_8x8x8(sched.tile.m, sched.tile.n, sched.tile.k);
            if should_use_coopmat(&shape) {
                Ok(matmul_tc_wgsl_tiled())
            } else {
                Ok(emit_wgsl(&BuiltinKernel::Gemm.spec(), *sched)?.source)
            }
        }
        Op::MatMul { tc: false, .. } => Ok(emit_wgsl(&BuiltinKernel::Gemm.spec(), *sched)?.source),
        Op::Gemv { .. } => Ok(emit_wgsl(&BuiltinKernel::Gemv.spec(), *sched)?.source),
        Op::ElementwiseAdd => emit_elementwise_wgsl("+", wg),
        Op::ElementwiseMul => emit_elementwise_wgsl("*", wg),
        Op::Silu => emit_silu_wgsl(wg),
        Op::RmsNorm { eps } => emit_rmsnorm_wgsl(*eps, wg),
        Op::RoPE { theta } => emit_rope_wgsl(*theta, wg),
        Op::PrefixScan => emit_prefix_scan_wgsl(wg),
        Op::RadixHistogram { shift } => emit_radix_histogram_wgsl(*shift, wg),
        Op::RadixScatter { shift } => emit_radix_scatter_wgsl(*shift, wg),
        _ => Ok(emit_wgsl(&BuiltinKernel::AffineF32.spec(), *sched)?.source),
    }
}

fn emit_kernel_body(
    source: &mut String,
    kernel: &KernelSpec,
    schedule: Schedule,
) -> Result<(), ForgeError> {
    match kernel.id.as_str() {
        "topk" => return emit_topk_wgsl(source, kernel, schedule),
        "fused-ffn" => return emit_ffn_wgsl(source, kernel, schedule),
        "p64-project" => return emit_p64_wgsl(source, kernel, schedule),
        "ternary-gemv" => return emit_ternary_gemv_wgsl(source, kernel, schedule),
        "gemm" => return emit_gemm_wgsl(source, kernel, schedule),
        "gemv" => return emit_gemv_wgsl(source, kernel, schedule),
        "fft" => return emit_fft_wgsl(source, kernel, schedule),
        _ => {}
    }

    if kernel.id == "ray-probe" {
        writeln!(source, "enable etalon_ray_query;")
            .map_err(|error| ForgeError::Emission(error.to_string()))?;
    }

    if kernel.id == "affine-f32" {
        writeln!(
            source,
            "\nstruct AffineParams {{\n    length: u32,\n    scale: f32,\n    bias: f32,\n    _pad: u32,\n}}"
        )
        .map_err(|error| ForgeError::Emission(error.to_string()))?;
    }

    writeln!(source).map_err(|error| ForgeError::Emission(error.to_string()))?;
    for buffer in &kernel.buffers {
        if buffer.element == BufferElement::AccelerationStructure {
            writeln!(
                source,
                "@group({}) @binding({}) var {}: acceleration_structure;",
                buffer.group, buffer.binding, buffer.name
            )
            .map_err(|error| ForgeError::Emission(error.to_string()))?;
            continue;
        }
        let access = match buffer.access {
            BufferAccess::StorageRead => "storage, read",
            BufferAccess::StorageReadWrite => "storage, read_write",
            BufferAccess::Uniform => "uniform",
        };
        let type_decl = match buffer.element {
            BufferElement::Scalar(ScalarType::F32) => "array<f32>",
            BufferElement::Scalar(ScalarType::U32) => "array<u32>",
            BufferElement::Scalar(ScalarType::I32) => "array<i32>",
            BufferElement::Scalar(ScalarType::U64Words) => "array<vec2<u32>>",
            BufferElement::AffineParams => "AffineParams",
            BufferElement::P64Words64 => "array<P64Words64>",
            BufferElement::AccelerationStructure => unreachable!("handled above"),
        };
        writeln!(
            source,
            "@group({}) @binding({}) var<{}> {}: {};",
            buffer.group, buffer.binding, access, buffer.name, type_decl
        )
        .map_err(|error| ForgeError::Emission(error.to_string()))?;
    }

    let wg = schedule.effective_workgroup_size();
    writeln!(
        source,
        "\nconst ITEMS_PER_INVOCATION: u32 = {}u;\nconst VECTOR_WIDTH: u32 = {}u;\n\n@compute @workgroup_size({})\nfn {}(@builtin(global_invocation_id) gid: vec3<u32>) {{",
        schedule.items_per_invocation, schedule.vector_width, wg, kernel.entry_point
    )
    .map_err(|error| ForgeError::Emission(error.to_string()))?;

    if kernel.id == "ray-probe" {
        writeln!(
            source,
            "    let i = gid.x;\n    if (i >= arrayLength(&hits)) {{ return; }}\n    let base = i * 8u;\n    let origin = vec3<f32>(rays[base], rays[base + 1u], rays[base + 2u]);\n    let direction = vec3<f32>(rays[base + 3u], rays[base + 4u], rays[base + 5u]);\n    let t_min = rays[base + 6u];\n    let t_max = rays[base + 7u];"
        )
        .map_err(|error| ForgeError::Emission(error.to_string()))?;
        emit_ops(source, &kernel.ops, "    ")?;
        writeln!(source, "    hits[i] = hit_t;\n}}")
            .map_err(|error| ForgeError::Emission(error.to_string()))?;
    } else if kernel.id == "affine-f32" {
        emit_affine_body(source, kernel, schedule)?;
    } else {
        writeln!(
            source,
            "    for (var item: u32 = 0u; item < ITEMS_PER_INVOCATION; item = item + 1u) {{\n        let global_id = gid.x * ITEMS_PER_INVOCATION + item;"
        )
        .map_err(|error| ForgeError::Emission(error.to_string()))?;
        emit_ops(source, &kernel.ops, "        ")?;
        writeln!(source, "    }}\n}}").map_err(|error| ForgeError::Emission(error.to_string()))?;
    }

    Ok(())
}

fn emit_affine_body(
    source: &mut String,
    kernel: &KernelSpec,
    schedule: Schedule,
) -> Result<(), ForgeError> {
    writeln!(
        source,
        "    for (var item: u32 = 0u; item < ITEMS_PER_INVOCATION; item = item + 1u) {{\n        let global_id = (gid.x * ITEMS_PER_INVOCATION + item) * VECTOR_WIDTH;"
    )
    .map_err(|error| ForgeError::Emission(error.to_string()))?;

    if schedule.vector_width == 1 {
        writeln!(source, "        if (global_id < params.length) {{")
            .map_err(|error| ForgeError::Emission(error.to_string()))?;
        emit_ops(source, &kernel.ops, "            ")?;
        writeln!(source, "        }}").map_err(|error| ForgeError::Emission(error.to_string()))?;
    } else {
        let constructor = (0..schedule.vector_width)
            .map(|index| format!("input[global_id + {index}u]"))
            .collect::<Vec<_>>()
            .join(", ");
        writeln!(
            source,
            "        if (global_id + {}u < params.length) {{\n            let value = vec{}<f32>({});\n            let transformed = value * vec{}<f32>(params.scale) + vec{}<f32>(params.bias);",
            schedule.vector_width - 1,
            schedule.vector_width,
            constructor,
            schedule.vector_width,
            schedule.vector_width
        )
        .map_err(|error| ForgeError::Emission(error.to_string()))?;
        let components = ["x", "y", "z", "w"];
        for index in 0..schedule.vector_width {
            writeln!(
                source,
                "            output[global_id + {index}u] = transformed.{};",
                components[index as usize]
            )
            .map_err(|error| ForgeError::Emission(error.to_string()))?;
        }
        writeln!(
            source,
            "        }} else {{\n            for (var component: u32 = 0u; component < VECTOR_WIDTH; component = component + 1u) {{\n                let global_id = global_id + component;\n                if (global_id < params.length) {{"
        )
        .map_err(|error| ForgeError::Emission(error.to_string()))?;
        emit_ops(source, &kernel.ops, "                    ")?;
        writeln!(source, "                }}\n            }}\n        }}")
            .map_err(|error| ForgeError::Emission(error.to_string()))?;
    }
    writeln!(source, "    }}\n}}").map_err(|error| ForgeError::Emission(error.to_string()))
}

fn emit_topk_wgsl(
    source: &mut String,
    kernel: &KernelSpec,
    schedule: Schedule,
) -> Result<(), ForgeError> {
    let wg = schedule.effective_workgroup_size();
    writeln!(
        source,
        "\nstruct TopKParams {{ length: u32, k: u32, block_size: u32, _pad: u32 }}\n@group(0) @binding(0) var<storage, read> input: array<f32>;\n@group(0) @binding(1) var<storage, read_write> output: array<f32>;\n@group(0) @binding(2) var<uniform> params: TopKParams;"
    )
    .map_err(|error| ForgeError::Emission(error.to_string()))?;

    for shared in &kernel.shared_memory {
        writeln!(
            source,
            "var<workgroup> {}: array<{}, {}>;",
            shared.name,
            shared.element.wgsl_name(),
            shared.length.resolve(wg)
        )
        .map_err(|error| ForgeError::Emission(error.to_string()))?;
    }

    writeln!(
        source,
        r#"@compute @workgroup_size({wg})
fn {entry}(@builtin(local_invocation_id) lid: vec3<u32>, @builtin(workgroup_id) wid: vec3<u32>) {{
    let tid = lid.x;
    let block = wid.x;
    let gidx = block * {wg}u + tid;
    let sentinel = bitcast<f32>(0xff7fffffu);
    var v = sentinel;
    if (gidx < params.length) {{ v = input[gidx]; }}
    s_val[tid] = v;
    s_idx[tid] = tid;
    workgroupBarrier();
    for (var i: u32 = 0u; i < params.k; i = i + 1u) {{
        r_val[tid] = s_val[tid];
        r_idx[tid] = s_idx[tid];
        workgroupBarrier();
        for (var stride: u32 = {wg}u / 2u; stride > 0u; stride = stride / 2u) {{
            if (tid < stride && r_val[tid + stride] > r_val[tid]) {{
                r_val[tid] = r_val[tid + stride];
                r_idx[tid] = r_idx[tid + stride];
            }}
            workgroupBarrier();
        }}
        if (tid == 0u) {{
            output[block * params.k + i] = r_val[0];
            s_val[r_idx[0]] = sentinel;
        }}
        workgroupBarrier();
    }}
}}"#,
        wg = wg,
        entry = kernel.entry_point
    )
    .map_err(|error| ForgeError::Emission(error.to_string()))
}

fn emit_ffn_wgsl(
    source: &mut String,
    kernel: &KernelSpec,
    schedule: Schedule,
) -> Result<(), ForgeError> {
    let wg = schedule.effective_workgroup_size();
    writeln!(
        source,
        r#"struct FfnParams {{ input_size: u32, hidden_size: u32, output_size: u32, _pad: u32 }}
@group(0) @binding(0) var<storage, read> input: array<f32>;
@group(0) @binding(1) var<storage, read> w1: array<f32>;
@group(0) @binding(2) var<storage, read> w2: array<f32>;
@group(0) @binding(3) var<storage, read_write> output: array<f32>;
@group(0) @binding(4) var<uniform> params: FfnParams;

@compute @workgroup_size({wg})
fn {entry}(@builtin(global_invocation_id) gid: vec3<u32>) {{
    let o = gid.x;
    if (o >= params.output_size) {{ return; }}
    var acc = 0.0;
    for (var h: u32 = 0u; h < params.hidden_size; h = h + 1u) {{
        var hv = 0.0;
        let w1_row = h * params.input_size;
        for (var i: u32 = 0u; i < params.input_size; i = i + 1u) {{
            hv = hv + w1[w1_row + i] * input[i];
        }}
        let g = 0.5 * hv * (1.0 + tanh(0.7978845608 * (hv + 0.044715 * hv * hv * hv)));
        acc = acc + w2[o * params.hidden_size + h] * g;
    }}
    output[o] = acc;
}}"#,
        wg = wg,
        entry = kernel.entry_point
    )
    .map_err(|error| ForgeError::Emission(error.to_string()))
}

fn emit_p64_wgsl(
    source: &mut String,
    kernel: &KernelSpec,
    schedule: Schedule,
) -> Result<(), ForgeError> {
    let wg = schedule.effective_workgroup_size();
    writeln!(
        source,
        r#"struct P64Words64 {{ lanes: array<vec4<u32>, 4> }}
@group(0) @binding(0) var<storage, read> input: array<P64Words64>;
@group(0) @binding(1) var<storage, read> weights: array<f32>;
@group(0) @binding(2) var<storage, read_write> output: array<f32>;

@compute @workgroup_size({wg})
fn {entry}(@builtin(global_invocation_id) gid: vec3<u32>) {{
    let r = gid.x;
    if (r >= arrayLength(&output)) {{ return; }}
    let rec = input[r];
    var acc = 0.0;
    for (var w: u32 = 0u; w < 16u; w = w + 1u) {{
        acc = acc + weights[w] * f32(rec.lanes[w / 4u][w % 4u]);
    }}
    output[r] = acc;
}}"#,
        wg = wg,
        entry = kernel.entry_point
    )
    .map_err(|error| ForgeError::Emission(error.to_string()))
}

fn emit_ternary_gemv_wgsl(
    source: &mut String,
    kernel: &KernelSpec,
    schedule: Schedule,
) -> Result<(), ForgeError> {
    let wg = schedule.effective_workgroup_size();
    writeln!(
        source,
        r#"struct TernaryGemvParams {{ m: u32, k: u32, k_words: u32, _pad: u32 }}
@group(0) @binding(0) var<storage, read> x: array<f32>;
@group(0) @binding(1) var<storage, read> w_packed: array<u32>;
@group(0) @binding(2) var<storage, read> scale: array<f32>;
@group(0) @binding(3) var<storage, read_write> output: array<f32>;
@group(0) @binding(4) var<uniform> params: TernaryGemvParams;

@compute @workgroup_size({wg})
fn {entry}(@builtin(global_invocation_id) gid: vec3<u32>) {{
    let o = gid.x;
    if (o >= params.m) {{ return; }}
    var acc = 0.0;
    let row_base = o * params.k_words;
    for (var word_idx: u32 = 0u; word_idx < params.k_words; word_idx = word_idx + 1u) {{
        let word = w_packed[row_base + word_idx];
        for (var lane: u32 = 0u; lane < 16u; lane = lane + 1u) {{
            let i = word_idx * 16u + lane;
            if (i >= params.k) {{ break; }}
            let code = (word >> (lane * 2u)) & 3u;
            var tern = 0.0;
            if (code == 1u) {{ tern = 1.0; }} else if (code == 2u) {{ tern = -1.0; }}
            acc = acc + tern * x[i];
        }}
    }}
    output[o] = scale[o] * acc;
}}"#,
        wg = wg,
        entry = kernel.entry_point
    )
    .map_err(|error| ForgeError::Emission(error.to_string()))
}
