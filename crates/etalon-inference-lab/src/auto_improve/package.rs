use super::*;
pub fn neighbors<M: LabMode>(c: &LabConfig<M>) -> Vec<LabConfig<M>> {
    let mut out = Vec::new();
    let mut flip = |mut x: LabConfig<M>, label_sfx: &str| {
        x.label = format!("{}_{label_sfx}", c.label);
        out.push(x);
    };
    let mut a = c.clone();
    a.coop = !a.coop;
    flip(a, "flip_coop");
    let mut b = c.clone();
    b.kv_int8 = !b.kv_int8;
    flip(b, "flip_kv");
    let mut d = c.clone();
    d.resident = !d.resident;
    flip(d, "flip_res");
    if c.mode == M::PORTABLE {
        let mut e = c.clone();
        e.mode = M::FAST_VERIFY;
        flip(e, "to_fast_verify");
    }
    out
}

pub(super) fn build_methodology<M: LabMode>(
    best: &Option<TrialResult<M>>,
    ollama: Option<f64>,
    a_gap: Option<f64>,
    audit: &InstrumentReports,
    trials: &[TrialResult<M>],
    gens: u32,
) -> String {
    let mut s = String::from("# Lab auto-improve methodology lock-in\n\n");
    s.push_str(
        "Generated by `qualia-cli llm lab auto` — **evidence-based**, not LLM kernel rewrite.\n\n",
    );
    s.push_str("Research candidate only. Aggregate samples select this configuration; independent held-out paired confirmation and Qualia activation are separate. Legacy proxy/unknown-backend records cannot qualify production.\n\n## Best config\n\n");
    if let Some(b) = best {
        s.push_str(&format!(
            "- label: `{}`\n- tok_s: {:?}\n- toggles: `{}`\n\n",
            b.config.label,
            b.tok_s,
            b.config.toggles_json()
        ));
    } else {
        s.push_str("- **none** (all trials failed)\n\n");
    }
    s.push_str("## Ollama yardstick\n\n");
    s.push_str(&format!(
        "- ollama_tok_s: {:?}\n- a_gap: {:?}\n\n",
        ollama, a_gap
    ));
    s.push_str("## Audit notes (unfinished integration)\n\n");
    for n in &audit.notes {
        s.push_str(&format!("- {n}\n"));
    }
    s.push_str(&format!(
        "\n## Search stats\n\n- trials: {}\n- generations: {gens}\n- ffn_fusion_in_resident: {}\n\n",
        trials.len(),
        audit.ffn_fusion_in_resident_decode
    ));
    s.push_str("## Next engineering (not search)\n\n");
    s.push_str("1. **T-A1** (done wiring) — re-optimise fused_ffn body (coop/shared act) if A-gap still open.\n");
    s.push_str("2. **T-A2** CUDA hidden-on-device full layer stack.\n");
    s.push_str("3. Re-run `lab auto` after each; only lock-in when A-gap phase targets improve.\n");
    s.push_str("\n## Apply\n\n```powershell\n. .\\experiments\\inference-lab\\lockin\\apply-best.ps1\n```\n");
    s
}

/// Renders a lock-in package summary.
pub fn format_lockin_summary<M: LabMode>(pkg: &LockInPackage<M>) -> String {
    format!(
        "LOCK-IN SUMMARY\n  out_dir:     {}\n  trials:      {}\n  generations: {}\n  elapsed_s:   {:.1}\n  best_tok_s:  {:?}\n  best_label:  {}\n  ollama_tok_s:{:?}\n  a_gap:       {:?}\n",
        pkg.out_dir.display(),
        pkg.trials,
        pkg.generations,
        pkg.elapsed_secs,
        pkg.best.as_ref().and_then(|b| b.tok_s),
        pkg.best
            .as_ref()
            .map(|b| b.config.label.as_str())
            .unwrap_or("none"),
        pkg.ollama_tok_s,
        pkg.a_gap
    )
}

pub(super) fn aggregate_trials<M: LabMode>(trials: &[TrialResult<M>]) -> Vec<TrialResult<M>> {
    let mut groups: Vec<(TrialResult<M>, f64, usize)> = Vec::new();
    for trial in trials {
        let Some(value) = trial.tok_s.filter(|v| v.is_finite() && *v > 0.0) else {
            continue;
        };
        let c = &trial.config;
        if let Some((_, sum, count)) = groups.iter_mut().find(|(old, _, _)| {
            let o = &old.config;
            o.resident == c.resident
                && o.coop == c.coop
                && o.ffn_fusion == c.ffn_fusion
                && o.kv_int8 == c.kv_int8
                && o.mode == c.mode
                && o.backend == c.backend
        }) {
            *sum += value;
            *count += 1;
        } else {
            groups.push((trial.clone(), value, 1));
        }
    }
    let mut ranked: Vec<_> = groups
        .into_iter()
        .map(|(mut trial, sum, count)| {
            trial.tok_s = Some(sum / count as f64);
            trial
        })
        .collect();
    ranked.sort_by(|a, b| {
        b.tok_s
            .unwrap()
            .total_cmp(&a.tok_s.unwrap())
            .then_with(|| a.config.label.cmp(&b.config.label))
    });
    ranked
}
